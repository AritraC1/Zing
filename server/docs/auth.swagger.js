/**
 * @swagger
 * /auth/keys/register:
 *   post:
 *     summary: Upload Signal Protocol key material for a device
 *     description: >
 *       Stores the client's public identity key, signed prekey and a batch
 *       of one-time prekeys. Private keys never leave the device. Requires
 *       an authenticated session; the device must belong to the caller.
 *     tags: [Auth]
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - deviceId
 *               - identityPublicKey
 *               - signedPreKeyId
 *               - signedPreKeyPublic
 *               - signedPreKeySignature
 *               - preKeys
 *             properties:
 *               deviceId:
 *                 type: string
 *                 format: uuid
 *                 example: 3fa85f64-5717-4562-b3fc-2c963f66afa6
 *               identityPublicKey:
 *                 type: string
 *                 format: base64
 *                 example: BASE64_PUBLIC_KEY
 *               signedPreKeyId:
 *                 type: integer
 *                 example: 1
 *               signedPreKeyPublic:
 *                 type: string
 *                 format: base64
 *                 example: BASE64_PUBLIC_KEY
 *               signedPreKeySignature:
 *                 type: string
 *                 format: base64
 *                 example: BASE64_SIGNATURE
 *               preKeys:
 *                 type: array
 *                 description: One-time prekey public keys (public only)
 *                 items:
 *                   type: object
 *                   required: [keyId, publicKey]
 *                   properties:
 *                     keyId:
 *                       type: integer
 *                       example: 101
 *                     publicKey:
 *                       type: string
 *                       format: base64
 *                       example: BASE64_PUBLIC_KEY
 *     responses:
 *       200:
 *         description: Key material registered
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 data:
 *                   type: object
 *                   properties:
 *                     deviceId:
 *                       type: string
 *                     registered:
 *                       type: boolean
 *                       example: true
 *                     preKeysUploaded:
 *                       type: integer
 *                       example: 100
 *                     preKeyCount:
 *                       type: integer
 *                       example: 100
 *       400:
 *         description: Invalid input
 *       401:
 *         description: Not authenticated
 *       403:
 *         description: Device belongs to another account
 *       404:
 *         description: Device not found
 */

/**
 * @swagger
 * /auth/keys/{userId}:
 *   get:
 *     summary: Fetch a user's prekey bundles (one per keyed device)
 *     description: >
 *       Returns the Signal prekey bundle for every keyed device of the
 *       user: identity key, signed prekey (id, public key, signature) and
 *       one unused one-time prekey which is consumed by this call. Used
 *       by initiators to run the X3DH handshake. Emits `keys:low` to the
 *       key owner when a device's one-time prekey count runs low.
 *     tags: [Auth]
 *     parameters:
 *       - in: path
 *         name: userId
 *         required: true
 *         schema:
 *           type: string
 *           format: uuid
 *         example: 3fa85f64-5717-4562-b3fc-2c963f66afa6
 *     responses:
 *       200:
 *         description: Prekey bundles fetched
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 data:
 *                   type: object
 *                   properties:
 *                     userId:
 *                       type: string
 *                     bundles:
 *                       type: array
 *                       items:
 *                         type: object
 *                         properties:
 *                           deviceId:
 *                             type: string
 *                           deviceType:
 *                             type: string
 *                             example: web
 *                           identityPublicKey:
 *                             type: string
 *                             example: BASE64_PUBLIC_KEY
 *                           signedPreKey:
 *                             type: object
 *                             properties:
 *                               keyId:
 *                                 type: integer
 *                               publicKey:
 *                                 type: string
 *                               signature:
 *                                 type: string
 *                           oneTimePreKey:
 *                             type: object
 *                             nullable: true
 *                             description: Null when the device has no unused one-time prekeys
 *                             properties:
 *                               keyId:
 *                                 type: integer
 *                               publicKey:
 *                                 type: string
 *                           preKeyCount:
 *                             type: integer
 *                             description: Unused one-time prekeys remaining on the device
 *       401:
 *         description: Not authenticated
 *       404:
 *         description: User not found or has no keyed devices
 */

